"""Embed version-pinned worldgen configuration facts, never Java code.

Requires the already SHA1-verified official server bundle and its extracted jar.
The native executable uses only the generated data; Java is not a dependency.
"""
import hashlib
import json
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SHA1 = '64bb6d763bed0a9f1d632ec347938594144943ed'
folder = ROOT / '.tools/vanilla-1.21.11'
if hashlib.sha1((folder / 'server.jar').read_bytes()).hexdigest() != SHA1:
    raise ValueError('Wrong official server bundle')
with zipfile.ZipFile(folder / 'server.jar') as bundle:
    inner = bundle.read('META-INF/versions/1.21.11/server-1.21.11.jar')
import io
with zipfile.ZipFile(io.BytesIO(inner)) as jar:
    entries = {}
    for name in sorted(jar.namelist()):
        tag_prefix = 'data/minecraft/tags/block/'
        if name.startswith(tag_prefix) and name.endswith('.json'):
            entries['block_tag/'+name[len(tag_prefix):-5]] = json.loads(jar.read(name))
            continue
        prefix = 'data/minecraft/worldgen/'
        if not name.startswith(prefix) or not name.endswith('.json'):
            continue
        relative = name[len(prefix):-5]
        kind, key = relative.split('/', 1)
        if kind in ('noise', 'density_function', 'biome') or relative == 'noise_settings/overworld' or relative in (
                'configured_carver/cave', 'configured_carver/cave_extra_underground', 'configured_carver/canyon'):
            entries[relative] = json.loads(jar.read(name))

out = ['// Generated by tools/generate-density-data.py. Minecraft 1.21.11 configuration facts.',
       '#pragma once', '#include <cstdint>', 'namespace cudacraft::density_data {',
       'struct Entry { const char* kind; const char* name; const char* json; };',
       'inline constexpr Entry entries[] = {']
for relative, value in entries.items():
    kind, key = relative.split('/', 1)
    # Tree/feature configuration is not consumed by this stage.
    if kind == 'biome':
        carvers = value.get('carvers', [])
        if carvers and carvers != ['minecraft:cave', 'minecraft:cave_extra_underground', 'minecraft:canyon'] and carvers != 'minecraft:nether_cave':
            raise ValueError('Unexpected biome carver ordering: '+key)
        value = {k: value[k] for k in ('temperature', 'temperature_modifier') if k in value}
    data = json.dumps(value, separators=(',', ':'), ensure_ascii=True)
    literals = '\n'.join('R"mc(' + data[i:i+12000] + ')mc"' for i in range(0, len(data), 12000))
    out.append('{"' + kind + '","minecraft:' + key + '",' + literals + '},')
out.append('};')
# Canonical state names let the MIT generator use its own compact block IDs.
# No dependency on upstream 26.2 numeric registry order is allowed.
blocks = json.loads((folder / 'reports-1.21.11/reports/blocks.json').read_text())
out.extend(['struct State { const char* name; std::uint32_t id; };', 'inline constexpr State states[] = {'])
for name, block in sorted(blocks.items()):
    for state in block['states']:
        props = state.get('properties', {})
        canonical = name + ('[' + ','.join(k + '=' + v for k, v in sorted(props.items())) + ']' if props else '')
        out.append('{' + json.dumps(canonical) + ',' + str(state['id']) + '},')
out.append('};')
registries = json.loads((ROOT / '.tools/reference/loginPacket.json').read_text())['dimensionCodec']
out.append('inline constexpr const char* biome_names[] = {')
for entry in registries['minecraft:worldgen/biome']['entries']:
    out.append(json.dumps(entry['key']) + ',')
out.extend(['};', '}'])
target = ROOT / 'include/cudacraft/generated_density_data.hpp'
target.write_text('\n'.join(out) + '\n', encoding='utf-8')
(ROOT/'tools/density-data-manifest.json').write_text(json.dumps({
    'version':'1.21.11','server_sha1':SHA1,
    'inner_jar_sha256':hashlib.sha256(inner).hexdigest(),
    'blocks_report_sha256':hashlib.sha256((folder/'reports-1.21.11/reports/blocks.json').read_bytes()).hexdigest(),
    'wire_registry_sha256':hashlib.sha256((ROOT/'.tools/reference/loginPacket.json').read_bytes()).hexdigest(),
    'header_sha256':hashlib.sha256(target.read_bytes()).hexdigest(),
    'records':len(entries)
},indent=2)+'\n')
print(f'Embedded {len(entries)} configuration records and all 1.21.11 block states')
