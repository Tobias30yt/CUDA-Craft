"""Generate compact 1.21.11 conduction, light opacity and piston reaction tables."""
import argparse
import hashlib
from importlib import import_module
from itertools import groupby
import math
from pathlib import Path
import os
import subprocess
from zipfile import ZipFile

reference = import_module("capture-vanilla-biomes")


def write_collisions(path, states):
    shapes, boxes, offsets, state_shapes = {}, [], [0], []
    for shape in states:
        if shape not in shapes:
            shapes[shape] = len(shapes)
            boxes.extend(shape)
            offsets.append(len(boxes))
        state_shapes.append(shapes[shape])
    if len(shapes)>65535:
        raise ValueError("Collision shape index exceeds 16 bits")
    output = [
        "// Generated by tools/generate-vanilla-block-physics.py from official 1.21.11 registry states.",
        "#pragma once","#include <algorithm>","#include <array>","#include <cstdint>","#include <iterator>","#include <span>",
        "namespace cudacraft::simdata {",
        "struct CollisionBox { std::array<double,3> min,max; };",
        "inline constexpr CollisionBox collision_boxes[]={",
    ]
    for box in boxes:
        minimum,maximum = (",".join(map(str,box[offset:offset+3])) for offset in (0,3))
        output.append(f"    {{{{{minimum}}},{{{maximum}}}}},")
    before = ",".join(str(math.ceil(max(0,max(box[axis+3] for box in boxes)-1))) for axis in range(3))
    after = ",".join(str(math.ceil(max(0,-min(box[axis] for box in boxes)))) for axis in range(3))
    output += ["};",f"inline constexpr std::array<int,3> collision_before={{{before}}};",
               f"inline constexpr std::array<int,3> collision_after={{{after}}};",
               "inline constexpr std::uint32_t collision_offsets[]={"]
    for start in range(0,len(offsets),16):
        output.append("    "+",".join(map(str,offsets[start:start+16]))+",")
    output += ["};","inline constexpr std::uint32_t collision_state_ranges[]={"]
    end = -1
    values = []
    for shape,positions in groupby(state_shapes):
        end += sum(1 for _ in positions)
        values.append(f"0x{(end<<16)|shape:08x}")
    for start in range(0,len(values),10):
        output.append("    "+",".join(values[start:start+10])+",")
    output += [
        "};",
        "inline std::span<const CollisionBox> static_collision_boxes(int state) {",
        "    if(state<0)return {};",
        "    const auto end=std::end(collision_state_ranges);",
        "    const auto match=std::lower_bound(std::begin(collision_state_ranges),end,state,",
        "        [](std::uint32_t run,int value){return (run>>16)<static_cast<std::uint32_t>(value);});",
        "    if(match==end)return {};",
        "    const unsigned shape=*match&65535;",
        "    const auto begin=collision_offsets[shape];",
        "    return {collision_boxes+begin,collision_offsets[shape+1]-begin};",
        "}",
        "}",
    ]
    path.write_text("\n".join(output)+"\n",encoding="utf-8",newline="\n")
    print(f"Captured {len(shapes)} static collision shapes")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--java",required=True,type=Path)
    args = parser.parse_args()
    root = reference.ROOT
    folder = root/".tools/vanilla-1.21.11"
    jar = folder/"server.jar"
    if hashlib.sha1(jar.read_bytes()).hexdigest()!=reference.SHA1:
        raise ValueError("Wrong reference server JAR")
    inner = folder/"versions/1.21.11/server-1.21.11.jar"
    jars = [inner,*sorted((folder/"libraries").rglob("*.jar"))]
    with ZipFile(jar) as server:
        if hashlib.sha256(inner.read_bytes()).digest()!=hashlib.sha256(
                server.read("META-INF/versions/1.21.11/server-1.21.11.jar")).digest():
            raise ValueError("Wrong extracted reference server JAR")
    java = [str(args.java.resolve()),"-Dlog4j2.configurationFile=none","-cp",os.pathsep.join(map(str,jars))]
    helper = Path(__file__).with_name("CaptureVanillaBlockPhysics.java")
    result = subprocess.run([*java,str(helper)],cwd=folder,encoding="utf-8",capture_output=True,timeout=60)
    if result.returncode:
        raise RuntimeError(result.stderr+result.stdout)
    rows = []
    collisions = []
    for line in result.stdout.splitlines():
        fields = line.split()
        if len(fields)<8 or not all(value.isdecimal() for value in fields[:8]):
            continue
        block_id,conductor,opacity,reaction,block_entity,solid,signal,faces = map(int,fields[:8])
        if (block_id!=len(rows) or not 0<=opacity<=15 or not 0<=reaction<=4 or
                not 0<=faces<=63 or any(flag not in (0,1) for flag in (conductor,block_entity,solid,signal))):
            raise ValueError(f"Invalid reference block facts {fields}")
        rows.append((conductor,opacity,reaction,block_entity,solid,signal,faces))
        coordinates = tuple(map(float,fields[8:]))
        if len(coordinates)%6 or any(not math.isfinite(v) or abs(v)>2 for v in coordinates):
            raise ValueError(f"Invalid collision profile for state {block_id}")
        collisions.append(tuple(coordinates[i:i+6] for i in range(0,len(coordinates),6)))
    if len(rows)<29000:
        raise ValueError(f"Only {len(rows)} reference block states read")
    output = [
        "// Generated by tools/generate-vanilla-block-physics.py from official 1.21.11 registry states.",
        "#pragma once","#include <algorithm>","#include <cstdint>","#include <iterator>",
        "namespace cudacraft::simdata {",
        "enum class PushReaction { normal, destroy, block, ignore, push_only };",
        "struct BlockPhysics {",
        "    bool conductor; int opacity; PushReaction push; bool block_entity,solid,signal_source; int sturdy_faces;",
        "    bool sturdy(int face) const { return (sturdy_faces&(1<<face))!=0; }",
        "};",
        "// The upper bits give the last state in a run. The lower bits encode its flags.",
        "inline constexpr std::uint32_t block_physics_ranges[]={",
    ]
    end = -1
    values = []
    for (conductor,opacity,reaction,block_entity,solid,signal,faces),states in groupby(rows):
        end += sum(1 for _ in states)
        flags = conductor|(opacity<<1)|(reaction<<5)|(block_entity<<8)|(solid<<9)|(signal<<10)|(faces<<11)
        values.append(f"0x{(end<<17)|flags:08x}")
    for offset in range(0,len(values),10):
        output.append("    "+",".join(values[offset:offset+10])+",")
    output += [
        "};",
        "inline BlockPhysics block_physics(int state) {",
        "    if(state<0)return {};",
        "    const auto end=std::end(block_physics_ranges);",
        "    const auto match=std::lower_bound(std::begin(block_physics_ranges),end,state,",
        "        [](std::uint32_t entry,int value){return (entry>>17)<static_cast<std::uint32_t>(value);});",
        "    if(match==end)return {};",
        "    const auto flags=*match;",
        "    return {bool(flags&1),int((flags>>1)&15),static_cast<PushReaction>((flags>>5)&7),",
        "            bool(flags&256),bool(flags&512),bool(flags&1024),int((flags>>11)&63)};",
        "}",
        "}",
    ]
    (root/"include/cudacraft/block_physics.hpp").write_text("\n".join(output)+"\n",encoding="utf-8",newline="\n")
    write_collisions(root/"include/cudacraft/block_collision_data.hpp",collisions)
    print(f"Captured physics for {len(rows)} Vanilla block states")


if __name__=="__main__":
    main()
